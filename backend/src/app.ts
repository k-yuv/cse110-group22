import path from 'node:path';
import express from 'express';
import * as OpenApiValidator from 'express-openapi-validator';
import notesRouter from './features/notes/notes.router';
import questionsRouter from './features/questions/questions.router';
import aiImagesRouter from './features/aiImages/aiImages.router';
import { errorHandler } from './middleware/errorHandler';
import { IMAGES_DIR, IMAGES_URL } from './utils/images';

// ---------------------------------------------------------------
// Types shared across features. Import them with `import type`, e.g.
//   import type { Note } from '../../app';
// ---------------------------------------------------------------

// Matches the Note schema in backend/openapi.yaml.
export interface Note {
  id: string;
  title: string;
  created_at: string;
}

// Matches the Question schema in backend/openapi.yaml.
export interface Question {
  chapter: number;
  number: number;
  content: string;
  // Always exactly 4 answer choices. A choice is referred to by its position (0-3).
  choices: string[];
}

// How a question is saved in backend/data/questions.json. The correct choice
// is never sent to the client, so it isn't part of the Question schema.
export interface StoredQuestion extends Question {
  // Position (0-3) in `choices` of the correct answer.
  correctChoice: number;
}

// Matches the AnswerResult schema in backend/openapi.yaml.
export interface AnswerResult {
  correct: boolean;
}

// Matches the AiImage schema in backend/openapi.yaml.
export interface AiImage {
  id: string;
  // URL the frontend loads the picture from, e.g. /api/images/cat.jpg
  src: string;
  // Text description of the image, for screen readers.
  alt: string;
}

// How an image is saved in backend/data/aiImages.json. The answer (`isAi`) is
// never sent to the client, and `fileName` is turned into `src` before sending.
export interface StoredAiImage {
  id: string;
  // Name of the picture's file in backend/data/images/.
  fileName: string;
  alt: string;
  // True if the image was generated by AI.
  isAi: boolean;
}

const app = express();

app.use(express.json());

// Serves the picture files in backend/data/images/ as-is, e.g.
// GET /api/images/cat.jpg. This sits before the OpenAPI validator because
// these are plain files, not JSON routes. A file that doesn't exist falls
// through to the validator, which responds 404.
app.use(IMAGES_URL, express.static(IMAGES_DIR));

// Checks every request and response against backend/openapi.yaml. Bad
// requests are rejected with a 4xx before they reach a controller, routes
// missing from the spec respond 404, and a response that doesn't match its
// schema becomes a 500.
app.use(OpenApiValidator.middleware({
  apiSpec: path.join(__dirname, '../openapi.yaml'),
  validateRequests: true,
  validateResponses: true,
}));

app.get('/api/health', (req, res) => {
  res.json({ status: 'ok' });
});

// Feature routers. Each one handles every URL under its prefix.
app.use('/api/notes', notesRouter);
app.use('/api/chapters/:chapter/questions', questionsRouter);
app.use('/api/ai-images', aiImagesRouter);

// Must stay last: it only runs when something above passed along an error.
app.use(errorHandler);

export default app;
